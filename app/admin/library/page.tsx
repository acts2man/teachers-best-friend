import Link from "next/link";
import { getReteaching, getPlatformStats, supabaseAdmin } from "@/lib/supabase-admin";
import { reviewReteaching } from "@/app/admin/actions";
import { fmtUsd, fmtRel } from "@/components/admin/format";

export default async function LibraryPage({ searchParams }: { searchParams: Promise<{ status?: string; id?: string }> }) {
  const { status, id } = await searchParams;
  const [rows, stats] = await Promise.all([getReteaching(status || undefined), getPlatformStats()]);
  const detail = id ? (await supabaseAdmin().from("reteaching_library").select("*").eq("id", id).single()).data : null;

  const servedTotal = rows.reduce((a, r) => a + Number(r.times_served), 0);
  const genCost = rows.reduce((a, r) => a + Number(r.generation_cost_usd), 0);

  return (
    <>
      <h1>Reteaching library</h1>
      <p className="ad-sub">
        {stats.reteaching_entries} entries · {stats.reteaching_unreviewed} unreviewed · served {servedTotal} times from cache · {fmtUsd(genCost, 2)} to generate
        {servedTotal > 0 && genCost > 0 && <> · every entry served pays back {(servedTotal / rows.length).toFixed(1)}× on average</>}
      </p>

      <div className="toolbar">
        {[["", "All"], ["auto", "Unreviewed"], ["approved", "Approved"], ["flagged", "Flagged"], ["retired", "Retired"]].map(([k, l]) => (
          <Link key={k} href={`/admin/library${k ? `?status=${k}` : ""}`} className={`pill ${(status ?? "") === k ? "pill-ok" : "pill-mute"}`} style={{ textDecoration: "none" }}>{l}</Link>
        ))}
      </div>

      <div className="ad-grid two">
        <div className="panel" style={{ overflowX: "auto" }}>
          <table>
            <thead><tr><th>Standard</th><th>Misconception</th><th className="num">Served</th><th>Status</th><th></th></tr></thead>
            <tbody>
              {rows.length === 0 && <tr><td colSpan={5} className="muted">Empty. Entries appear as the pipeline generates reteaching material on cache misses.</td></tr>}
              {rows.map((r) => (
                <tr key={r.id} style={id === r.id ? { background: "var(--mark-tint)" } : undefined}>
                  <td><span className="mono">{r.standard_code}</span><div className="muted" style={{ fontSize: ".75rem" }}>{r.subject} · G{r.grade}{r.grade_band ? ` · ${r.grade_band}` : ""}</div></td>
                  <td><Link href={`/admin/library?${status ? `status=${status}&` : ""}id=${r.id}`}>{r.error_pattern_label}</Link><div className="muted" style={{ fontSize: ".75rem" }}>{r.title}</div></td>
                  <td className="num">{r.times_served}</td>
                  <td><span className={`pill ${r.review_status === "approved" ? "pill-ok" : r.review_status === "flagged" ? "pill-bad" : r.review_status === "retired" ? "pill-mute" : "pill-warn"}`}>{r.review_status}</span>{r.quality_score != null && <div className="muted" style={{ fontSize: ".72rem" }}>q {r.quality_score}</div>}</td>
                  <td className="muted" style={{ fontSize: ".75rem", whiteSpace: "nowrap" }}>{fmtRel(r.created_at)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <aside className="panel" style={{ padding: "1.1rem", position: "sticky", top: "1rem", alignSelf: "start" }}>
          {!detail ? <p className="muted" style={{ margin: 0 }}>Select an entry to read it and review it.</p> : (
            <>
              <h2 style={{ margin: "0 0 .25rem" }}>{detail.title}</h2>
              <p className="muted" style={{ fontSize: ".85rem" }}>{detail.error_pattern_label} · <span className="mono">{detail.error_pattern_key}</span> · generated by {detail.model ?? "unknown"} for {fmtUsd(detail.generation_cost_usd, 4)}</p>
              <div style={{ background: "#fff", border: "1px solid var(--rule-faint)", borderRadius: "var(--radius)", padding: ".9rem", fontSize: ".92rem", maxHeight: "24rem", overflow: "auto" }}>
                <RenderContent content={detail.content} />
              </div>
              <form action={reviewReteaching} style={{ marginTop: ".9rem", display: "flex", gap: ".5rem", alignItems: "center", flexWrap: "wrap" }}>
                <input type="hidden" name="id" value={detail.id} />
                <select name="status" defaultValue={detail.review_status}>
                  <option value="approved">Approve — keep serving</option>
                  <option value="flagged">Flag — needs a rewrite</option>
                  <option value="retired">Retire — stop serving, regenerate</option>
                  <option value="auto">Back to unreviewed</option>
                </select>
                <label style={{ fontSize: ".85rem" }}>Quality <input name="quality" type="number" min={0} max={5} step={0.5} defaultValue={detail.quality_score ?? ""} style={{ width: "4.5rem" }} /></label>
                <button className="btn btn-mark btn-sm">Save review</button>
              </form>
            </>
          )}
        </aside>
      </div>
    </>
  );
}

function RenderContent({ content }: { content: any }) {
  if (!content) return <p className="muted">No content.</p>;
  if (typeof content === "string") return <div style={{ whiteSpace: "pre-wrap" }}>{content}</div>;
  return (
    <dl style={{ margin: 0, display: "grid", gap: ".6rem" }}>
      {Object.entries(content).map(([k, v]) => (
        <div key={k}><dt style={{ fontWeight: 700, fontSize: ".8rem", color: "var(--ink-soft)", marginBottom: ".15rem" }}>{k.replace(/_/g, " ")}</dt><dd style={{ margin: 0, whiteSpace: "pre-wrap" }}>{typeof v === "string" ? v : Array.isArray(v) ? <ul style={{ margin: 0, paddingLeft: "1.1rem" }}>{v.map((x, i) => <li key={i}>{typeof x === "string" ? x : JSON.stringify(x)}</li>)}</ul> : JSON.stringify(v, null, 1)}</dd></div>
      ))}
    </dl>
  );
}
