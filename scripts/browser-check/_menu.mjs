import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const w = JSON.parse(readFileSync("scripts/browser-check/out/fixture.json", "utf8"));
const json = (b) => ({ status: 200, contentType: "application/json", body: JSON.stringify(b) });
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
for (const vp of [[390, 844], [412, 915]]) {
  const ctx = await b.newContext({ viewport: { width: vp[0], height: vp[1] } });
  await ctx.route("**/api/workspace", (r) => r.fulfill(json({ workspace: w, revision: 7, aiReady: true, authProvider: "supabase", impersonating: null })));
  await ctx.route("**/api/quota", (r) => r.fulfill(json({ plan_id: "starter", quota: 150, used: 20, remaining: 130, can_scan: true })));
  await ctx.route("**/api/events", (r) => r.fulfill({ status: 204, body: "" }));
  await ctx.route("**/api/scans/session**", (r) => r.fulfill(json({ state: null, revision: 0 })));
  const p = await ctx.newPage();
  await p.goto("http://127.0.0.1:3100/assessments?id=math-demo&tab=responses", { waitUntil: "networkidle" });
  await p.locator(".mobile-menu").click();
  const sheet = p.locator('[data-mobile="true"]');
  await sheet.waitFor({ timeout: 5000 });
  const target = p.locator('a[href="/assessments"]').first();
  console.log("first /classes link is inside the menu:", await target.evaluate((el) => !!el.closest('[data-mobile="true"]')));
  await target.click();
  await p.waitForTimeout(1500); console.log("url", p.url());
  await p.waitForTimeout(1200);
  const openAfterLink = await sheet.count() && await sheet.isVisible();
  await p.screenshot({ path: `scripts/browser-check/out/menu-after-link-${vp[0]}.png` });
  console.log(vp.join("x"), "menu still open after clicking a link:", openAfterLink);
  await p.goBack();
  await p.waitForTimeout(1200);
  console.log(vp.join("x"), "menu open after Back:", (await sheet.count()) && (await sheet.isVisible()));
  await ctx.close();
}
await b.close();
